arquivo <- grep("^--file=", commandArgs(FALSE), value = TRUE)
raiz <- if (length(arquivo)) dirname(normalizePath(sub("^--file=", "", arquivo[1]), winslash = "/")) else normalizePath("av2_global", winslash = "/")
.libPaths(c(file.path(dirname(raiz), ".biblioteca"), .libPaths()))
source(file.path(raiz, "R", "coleta.R"), encoding = "UTF-8")
brutos <- file.path(raiz, "dados", "brutos", c("iem_20261117.csv", "noaa_20261117.json"))
hashes <- tools::md5sum(brutos)
# O snapshot inicial é reproduzido dos bytes recebidos, sem consultar outra fonte.
dados <- combinar_observacoes(normalizar_iem(brutos[1]), normalizar_noaa(brutos[2]))
stopifnot(nrow(dados) > 0, length(unique(dados$estacao_id)) == 5L)
exportar <- dados
for (nome in c("observado_em", "instante")) exportar[[nome]] <- format(exportar[[nome]], "%Y-%m-%dT%H:%M:%SZ", tz = "UTC")
pasta <- file.path(raiz, "dados", "entrada")
dir.create(pasta, recursive = TRUE, showWarnings = FALSE)
write.csv(exportar, file.path(pasta, "observacoes_iniciais.csv"), row.names = FALSE, na = "NA", fileEncoding = "UTF-8")
conferir <- carregar_global(raiz)
stopifnot(nrow(conferir$dados) == nrow(dados), identical(tools::md5sum(brutos), hashes))
horas <- agregar_horas_globais(dados)
cat(nrow(dados), "boletins reais;", nrow(horas), "registros estação-hora.\n")
print(range(dados$observado_em))
print(table(horas$estacao))
